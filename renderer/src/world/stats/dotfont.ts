/** Width in dot pitches of `text` (5 per glyph + 1 gap, no trailing gap). */
export const dotWidth = (text: string) => Math.max(0, String(text).length * 6 - 1);

/**
 * Draw dot-matrix text. `pitch` = distance between dot centres in canvas px; the glyph cell is 5×7 pitches; `x` / `y` =
 * left / top edge (px); `color` = lit dot colour; `o.ghost` = alpha of unlit dots (0 = none).
 * @returns the drawn width in px
 */
export function drawDots(g: CanvasRenderingContext2D, text: string, x: number, y: number, pitch: number, color: string,
  o: { ghost?: number; align?: 'left' | 'center' | 'right'; dot?: number } = {}): number {
  const s = String(text).toUpperCase();
  const w = dotWidth(s) * pitch;
  if (o.align === 'center') x -= w / 2;
  else if (o.align === 'right') x -= w;
  const r = pitch * (o.dot ?? 0.42);
  const ghost = o.ghost ?? 0;
  if (ghost > 0) {
    g.globalAlpha = ghost;
    g.fillStyle = color;
    g.beginPath();
    for (let i = 0; i < s.length; i++) {
      const gx = x + i * 6 * pitch;
      for (let row = 0; row < 7; row++) for (let col = 0; col < 5; col++) {
        const cx = gx + (col + 0.5) * pitch, cy = y + (row + 0.5) * pitch;
        g.moveTo(cx + r, cy); g.arc(cx, cy, r, 0, Math.PI * 2);
      }
    }
    g.fill();
    g.globalAlpha = 1;
  }
  g.fillStyle = color;
  g.beginPath();
  for (let i = 0; i < s.length; i++) {
    const rows = GLYPHS[s[i]] ?? GLYPHS['?'];
    const gx = x + i * 6 * pitch;
    for (let row = 0; row < 7; row++) {
      const bits = rows[row];
      if (!bits) continue;
      for (let col = 0; col < 5; col++) {
        if (!(bits & (0x10 >> col))) continue;
        const cx = gx + (col + 0.5) * pitch, cy = y + (row + 0.5) * pitch;
        g.moveTo(cx + r, cy); g.arc(cx, cy, r, 0, Math.PI * 2);
      }
    }
  }
  g.fill();
  return w;
}

/**
 * The pixel-art Claude Code mascot (§11.5 pixel-Clawd homage), 13 × 9, two frames (frame 1 waves its right arm).
 * '#' = clay, 'o' = eye (ink), '.' = empty.
 */
export const PIXEL_CLAWD = [
  [
    '..#########..',
    '..#########..',
    '..##o###o##..',
    '#############',
    '#############',
    '..#########..',
    '..#########..',
    '..#.#...#.#..',
    '..#.#...#.#..',
  ],
  [
    '..#########.#',
    '..#########.#',
    '..##o###o####',
    '###########..',
    '###########..',
    '..#########..',
    '..#########..',
    '..#.#...#.#..',
    '..#.#...#.#..',
  ],
];

/**
 * Draw the pixel Clawd with square "pixels" of size `px` (top-left at x, y).
 */
export function drawPixelClawd(g: CanvasRenderingContext2D, x: number, y: number, px: number, frame = 0, clay = '#D97757', eye = '#1F1E1D') {
  const rows = PIXEL_CLAWD[frame % PIXEL_CLAWD.length];
  for (let r = 0; r < rows.length; r++) for (let c = 0; c < rows[r].length; c++) {
    const ch = rows[r][c];
    if (ch === '.') continue;
    g.fillStyle = ch === 'o' ? eye : clay;
    g.fillRect(Math.round(x + c * px), Math.round(y + r * px), Math.ceil(px), Math.ceil(px));
  }
}
